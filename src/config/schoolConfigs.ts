export interface SchoolConfig {
  id: string;
  name: string;
  shortName: string;
  nickname: string;
  logoUrl: string;
  conference: string;
  dataFile: string;
  /** Optional override for precomputed IP impact data */
  ipImpactDataFile?: string;
  /** Optional override for athlete roster metrics data */
  rosterDataFile?: string;
  /** Optional override for official team-account metrics data */
  teamDataFile?: string;
  colors: NilSchoolColors;
  peerSchools: PeerSchool[];
  benchmark: PeerSchool;
  /** Lowercase, no-@ handles to exclude from brand deals (NIL stores, collectives, team pages, etc.) */
  brandExclusions?: string[];
  /** Lowercase no-@ alias map: variant → canonical (for semantic deduplication) */
  brandAliases?: Record<string, string>;
  /** Explicit sponsored post IDs to exclude as false positives */
  sponsoredPostExclusions?: string[];
  /** Explicit post IDs to force-include as sponsored */
  sponsoredPostInclusions?: string[];
  /** Team sports to hide from the Teams tab (display name, e.g. "Swimming") */
  teamSportExclusions?: string[];
}

// ─── Helper to build PeerSchool entries ──────────────────────
